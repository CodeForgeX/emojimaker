/**
 * Source data for /emoji-combinations/ and its category pages.
 *
 * Every combo carries a short `meaning` — the format that wins these SERPs is a
 * labelled list ("👉👈 — feeling shy"), not a bare grid of characters. The meaning
 * is rendered as visible body text; only `combo` is copied to the clipboard.
 */

export interface ComboItem {
  /** The emoji sequence itself. This is what gets copied. */
  combo: string
  /** Short label: the vibe it reads as, or when to use it. Lowercase, no period. */
  meaning: string
}

export interface ComboSection {
  heading: string
  note: string
  combos: ComboItem[]
}

